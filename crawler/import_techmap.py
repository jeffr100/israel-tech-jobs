#!/usr/bin/env python3
"""Turn the Israeli Tech Map (github.com/mluggy/techmap, Open Database License) into finder entries.

The Tech Map lists about 8,000 active Israeli companies with their websites, careers pages and, for
some, their Comeet / Greenhouse / Lever job boards. This writes crawler/candidates_techmap.txt in the
same format as candidates.txt, which crawler/discover.py reads along with it:

    python3 crawler/import_techmap.py /path/to/techmap      # a checkout of the repo

The "Find more companies" workflow downloads a fresh copy and runs this before the finder, so new
companies added to the Tech Map are picked up automatically.
"""
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def comeet_from_jobs(path):
    """Company name -> Comeet board, from the job links in the Tech Map's jobs/*.csv files."""
    import csv
    out = {}
    for f in glob.glob(os.path.join(path, "jobs", "*.csv")):
        for r in csv.DictReader(open(f, encoding="utf-8-sig")):
            m = re.search(r"comeet\.com/jobs/([^/]+)/([0-9A-F]{2}\.[0-9A-F]{3})", r.get("url") or "", re.I)
            if m and r.get("company"):
                out.setdefault(r["company"].strip().lower(), f"{m.group(1)}/{m.group(2)}")
    return out


def directives(c, comeet_jobs):
    d = []
    comeet = c.get("comeetId") if c.get("comeetId") and "/" in c["comeetId"] else comeet_jobs.get(c["name"].strip().lower())
    if comeet:
        d.append("comeet " + comeet.strip("/"))
    if c.get("greenhouseId"):
        d.append("greenhouse " + c["greenhouseId"])
    if c.get("leverId"):
        d.append("lever " + c["leverId"])
    if not d:   # no known board: read the careers page, or the website's home and careers pages
        url = c.get("careersUrl") if c.get("careersUrl") and "linkedin.com" not in c["careersUrl"] else c.get("websiteUrl")
        if url:
            d.append("site " + url.strip())
    return d


def main(path):
    rows = []
    comeet_jobs = comeet_from_jobs(path)
    for f in sorted(glob.glob(os.path.join(path, "companies", "*.json"))):
        try:
            c = json.load(open(f, encoding="utf-8"))
        except ValueError:
            continue
        if not c.get("isActive") or not c.get("name"):
            continue
        name = re.sub(r"\s*\|\s*", " ", c["name"]).strip()
        large = "large" if c.get("size") in ("xl",) else ""
        d = directives(c, comeet_jobs)
        if d:
            rows.append(f"{name} | {large} | {'; '.join(d)}")
    out = os.path.join(HERE, "candidates_techmap.txt")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("# Generated by crawler/import_techmap.py from the Israeli Tech Map "
                 "(github.com/mluggy/techmap, ODbL). Don't edit; edit candidates.txt instead.\n")
        fh.write("\n".join(rows) + "\n")
    print(f"wrote {len(rows)} companies to {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "techmap")
